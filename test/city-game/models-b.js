function buildSchool(g, seed, c, r, v) {
    const st = SCHOOLS[v.id] || SCHOOLS.school;
    const h = 0.17 + 0.165 * st.floors;
    const gid = schoolGid.get(key(c, r));
    const linked = {};
    DIRS.forEach(d => { linked[d.name] = gid !== undefined && schoolGid.get(key(c + d.dc, r + d.dr)) === gid; });

    P(g, softG(0.85, 0.06, 0.85, 0.04), '#b7aea0', 0, 0.03, 0);
    P(g, softG(0.82, h, 0.82, 0.04), st.wall, 0, h / 2, 0);
    P(g, softG(0.88, 0.04, 0.88, 0.05), st.roof, 0, h + 0.02, 0);
    DIRS.forEach(d => {
        if (!linked[d.name]) return;
        const px = d.dc * 0.25, pz = d.dr * 0.25;
        P(g, B(d.dc !== 0 ? 0.5 : 0.82, h, d.dr !== 0 ? 0.5 : 0.82), st.wall, px, h / 2, pz);
        P(g, B(d.dc !== 0 ? 0.5 : 0.88, 0.04, d.dr !== 0 ? 0.5 : 0.88), st.roof, px, h + 0.02, pz);
    });

    // חזיתות חופשיות: רצועת חלונות לכל קומה, ובאחת מהן הכניסה (לכיוון הדרך)
    const exposed = DIRS.filter(d => !linked[d.name]);
    const entrance = exposed.find(d => roadAt(c + d.dc, r + d.dr)) || exposed[0];
    exposed.forEach(d => {
        const f = sub(g, 0, 0, 0, Math.atan2(d.dc, d.dr));
        f.userData.d = 0.41;
        const isEntr = d === entrance;
        for (let fl = 0; fl < st.floors; fl++) {
            const y = 0.15 + fl * 0.165;
            if (isEntr && fl === 0) {
                [-0.26, 0.26].forEach(x => { P(f, B(0.19, 0.11, 0.01), '#ffffff', x, y, 0.41); G(f, B(0.16, 0.085, 0.014), x, y, 0.411); });
            } else {
                P(f, B(0.66, 0.11, 0.01), '#ffffff', 0, y, 0.41);
                G(f, B(0.63, 0.085, 0.014), 0, y, 0.411, fl % 2 === 1);
                [-0.16, 0, 0.16].forEach(x => P(f, B(0.012, 0.085, 0.018), '#ffffff', x, y, 0.411));
            }
        }
        if (isEntr) {
            door(f, 0, 0.17, 0.2, '', { glass: true, frame: st.roof });
            P(f, B(0.012, 0.2, 0.024), st.roof, 0, 0.1, 0.413);
            P(f, B(0.3, 0.02, 0.1), st.roof, 0, 0.235, 0.455);
            [-0.13, 0.13].forEach(x => P(f, C(0.008, 0.008, 0.22, 5), '#ffffff', x, 0.115, 0.495));
        }
    });

    // דגל רק על חלקה אחת בכל קבוצה מאוחדת, וסמל על הגג לפי מה שלומדים
    if (st.flag && schoolAnchors.has(key(c, r))) flag(g, -0.32, h + 0.04, -0.32, st.flag, 0.34);
    const e = sub(g, 0.12, h + 0.04, 0.06);
    (SCHOOL_TOPS[v.id] || SCHOOL_TOPS.school)(e);
    solarHeater(g, -0.2, h + 0.04, 0.24);
    return h + 0.3;
}

